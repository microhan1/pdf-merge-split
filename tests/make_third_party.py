# -*- coding: utf-8 -*-
"""Write THIRD_PARTY_LICENSES.txt from the packages installed in the build environment.

    python tests/make_third_party.py

Lists every distribution PyInstaller would bundle for this program (the
requirements and what they pull in), with name, version, license and source,
followed by the full license texts that ship with those packages and with
Python itself. Run it in the environment that builds the exe, before a release.
"""
from __future__ import annotations

import importlib.metadata as md
import os
import sys
import sysconfig

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD_PARTY_LICENSES.txt")

TOP = ["PyMuPDF", "Pillow", "tkinterdnd2"]
EXTRA = {   # not pip packages, but inside the exe
    "Python": (sysconfig.get_python_version(), "Python Software Foundation License Version 2 (with the third-party terms listed in it: OpenSSL, libffi, bzip2, Zstandard, Tcl/Tk, the Microsoft Distributable Code)", "https://www.python.org"),
    "Tcl/Tk": ("8.6", "Tcl/Tk license (BSD-style)", "https://www.tcl-lang.org"),
    "tkdnd (inside tkinterdnd2)": ("2.x", "MIT License", "https://github.com/petasis/tkdnd"),
    "PyInstaller bootloader": (md.version("pyinstaller"), "GPL-2.0-or-later with the Bootloader Exception (the exe may carry any license)", "https://github.com/pyinstaller/pyinstaller"),
}


def closure(names: list[str]) -> list[str]:
    seen, order = set(), []

    def visit(name: str) -> None:
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            return
        key = dist.metadata["Name"]
        if key.lower() in seen:
            return
        seen.add(key.lower())
        order.append(key)
        for req in dist.requires or []:
            if ";" in req and "extra ==" in req:
                continue
            dep = req.split(";")[0].split("[")[0]
            dep = dep.split(" ")[0].split(">")[0].split("<")[0].split("=")[0].split("!")[0].split("~")[0].strip()
            if dep:
                visit(dep)

    for n in names:
        visit(n)
    return order


def license_of(dist) -> str:
    meta = dist.metadata
    lic = meta.get("License-Expression") or meta.get("License") or ""
    if not lic or len(lic) > 80:
        for c in meta.get_all("Classifier") or []:
            if c.startswith("License ::"):
                lic = c.split("::")[-1].strip()
                break
    return lic or "see the license file below"


def license_texts(dist) -> list[tuple[str, str]]:
    out = []
    for f in dist.files or []:
        name = f.name.lower()
        if ("licen" in name or "copying" in name or "notice" in name) and ".dist-info" in str(f) and not name.endswith((".py", ".pyc")):
            try:
                out.append((f.name, f.locate().read_text(encoding="utf-8", errors="replace")))
            except Exception:
                pass
    return out


def main() -> int:
    lines = ["Third-party software in pdf-merge-split.exe", "=" * 44, "",
             "pdf-merge-split's own code is licensed under the GNU AGPL-3.0 (see LICENSE).",
             "The released exe also contains the components below. PyMuPDF/MuPDF is AGPL-3.0,",
             "so the exe as a whole is distributed under the AGPL-3.0.", "",
             "Corresponding source of an exe: this repository at the tag of its release",
             "(https://github.com/microhan1/pdf-merge-split/tags), built with build.bat",
             "(PyInstaller --onefile from main.py). Versions below are those of the build",
             "environment at the time this file was generated by tests/make_third_party.py.", "",
             "Components", "-" * 10]
    dists = closure(TOP)
    texts: list[tuple[str, str, str]] = []
    for name in dists:
        d = md.distribution(name)
        home = d.metadata.get("Home-page") or ""
        if not home:
            for u in d.metadata.get_all("Project-URL") or []:
                if u.lower().startswith(("source", "homepage", "repository")):
                    home = u.split(",", 1)[1].strip()
                    break
        lines.append(f"- {name} {d.version}")
        lines.append(f"    License: {license_of(d)}")
        if home:
            lines.append(f"    Source:  {home}")
        for fname, text in license_texts(d):
            texts.append((f"{name} {d.version}", fname, text))
    for name, (ver, lic, home) in EXTRA.items():
        lines.append(f"- {name} {ver}")
        lines.append(f"    License: {lic}")
        lines.append(f"    Source:  {home}")
    py_lic = os.path.join(sysconfig.get_paths()["data"], "LICENSE.txt")
    if os.path.exists(py_lic):
        texts.append((f"Python {sysconfig.get_python_version()}", "LICENSE.txt", open(py_lic, encoding="utf-8", errors="replace").read()))
    texts.append(("PyMuPDF (MuPDF)", "AGPL-3.0", open(os.path.join(ROOT, "LICENSE"), encoding="utf-8").read()))
    lines += ["", "", "License texts", "=" * 13]
    for pkg, fname, text in texts:
        lines += ["", "", "=" * 78, f"{pkg} - {fname}", "=" * 78, "", text.rstrip()]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(OUT, len(dists), "packages,", len(texts), "license texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
